#!/usr/bin/env python3
"""
validate_fashionpedia_spatial_manifest.py

Validates the integrity, schema, geometry calculations, part association uniqueness,
split constancy, and label evidence of the spatial dataset manifest generated by Milestone AI-4B.

Usage:
    python ai_training/scripts/validate_fashionpedia_spatial_manifest.py \
      --manifest-dir ai_training/data/processed/fashionpedia_spatial_manifest \
      --base-manifest ai_training/data/processed/fashionpedia_manifest/all_instances.jsonl \
      --classes ai_training/config/classes.json \
      --association-config ai_training/config/part_association.json
"""

import sys
import os
import json
import math
import argparse


def validate_spatial_manifest(manifest_dir, base_manifest_path, classes_path, assoc_config_path=None, association_config=None):
    assoc_config_path = assoc_config_path or association_config
    print("==================================================")
    print("FASHIONPEDIA SPATIAL MANIFEST VALIDATION RUN")
    print("==================================================")
    print(f"Spatial Manifest Directory: {os.path.abspath(manifest_dir)}")

    # Check files exist
    all_spatial_file = os.path.join(manifest_dir, "all_instances_spatial.jsonl")
    train_ready_file = os.path.join(manifest_dir, "training_ready_spatial.jsonl")
    manual_review_file = os.path.join(manifest_dir, "manual_review_spatial.jsonl")
    rejected_file = os.path.join(manifest_dir, "rejected_spatial.jsonl")
    accepted_assoc_file = os.path.join(manifest_dir, "accepted_associations.jsonl")
    ambig_assoc_file = os.path.join(manifest_dir, "ambiguous_associations.jsonl")
    unassoc_parts_file = os.path.join(manifest_dir, "unassociated_parts.jsonl")
    summary_file = os.path.join(manifest_dir, "spatial_summary.json")

    for p in [all_spatial_file, train_ready_file, manual_review_file, rejected_file, accepted_assoc_file, ambig_assoc_file, unassoc_parts_file, summary_file, base_manifest_path, classes_path, assoc_config_path]:
        if not os.path.exists(p):
            print(f"VALIDATION FAILED: File not found: {p}", file=sys.stderr)
            sys.exit(1)

    # Load classes and assoc config
    with open(classes_path, "r", encoding="utf-8") as f:
        classes_data = json.load(f)
    with open(assoc_config_path, "r", encoding="utf-8") as f:
        assoc_config = json.load(f)
    with open(summary_file, "r", encoding="utf-8") as f:
        summary_data = json.load(f)

    target_heads = list(classes_data["outputs"].keys())
    valid_labels_per_head = {h: set(classes_data["outputs"][h]["classes"]) for h in target_heads}
    eligible_parents = set(assoc_config.get("eligible_parent_category_ids", [0, 1]))
    min_part_cov = assoc_config.get("minimum_part_coverage", 0.80)
    req_centre_inside = assoc_config.get("centre_inside_parent", True)
    min_score_margin = assoc_config.get("minimum_score_margin", 0.15)

    # Load JSONL records
    def load_jsonl(filepath):
        with open(filepath, "r", encoding="utf-8") as f:
            return [json.loads(line) for line in f]

    all_spatial_recs = load_jsonl(all_spatial_file)
    train_ready_recs = load_jsonl(train_ready_file)
    manual_review_recs = load_jsonl(manual_review_file)
    rejected_recs = load_jsonl(rejected_file)
    accepted_assoc_recs = load_jsonl(accepted_assoc_file)
    ambig_assoc_recs = load_jsonl(ambig_assoc_file)
    unassoc_parts_recs = load_jsonl(unassoc_parts_file)
    base_recs = load_jsonl(base_manifest_path)

    print(f"Loaded {len(all_spatial_recs)} total spatial instance records")

    # 1. Base manifest consistency & split invariance check
    base_by_id = {r["source_annotation_id"]: r for r in base_recs}
    spatial_by_id = {r["source_annotation_id"]: r for r in all_spatial_recs}

    if len(all_spatial_recs) != len(base_recs):
        print(f"VALIDATION FAILED: Base instance count ({len(base_recs)}) != spatial instance count ({len(all_spatial_recs)})", file=sys.stderr)
        sys.exit(1)

    for ann_id, base_r in base_by_id.items():
        if ann_id not in spatial_by_id:
            print(f"VALIDATION FAILED: Annotation ID {ann_id} missing in spatial manifest", file=sys.stderr)
            sys.exit(1)
        sp_r = spatial_by_id[ann_id]
        if sp_r["split"] != base_r["split"]:
            print(f"VALIDATION FAILED: Split changed for annotation ID {ann_id}: {base_r['split']} -> {sp_r['split']}", file=sys.stderr)
            sys.exit(1)

    print("1. Base manifest instance count & split invariance check: PASSED")

    # 2. Decision partition consistency check
    if len(all_spatial_recs) != (len(train_ready_recs) + len(manual_review_recs) + len(rejected_recs)):
        print("VALIDATION FAILED: Decision file record counts do not sum to total records", file=sys.stderr)
        sys.exit(1)
    print("2. Decision JSONL files partition consistency: PASSED")

    # 3. Accepted association checks: image_id match, eligible parent, unique part_annotation_id, geometry accuracy
    seen_part_ann_ids = set()
    ambig_part_ann_ids = set(a["part_annotation_id"] for a in ambig_assoc_recs)

    for assoc in accepted_assoc_recs:
        p_id = assoc["part_annotation_id"]
        if p_id in seen_part_ann_ids:
            print(f"VALIDATION FAILED: Part annotation ID {p_id} assigned to multiple parents", file=sys.stderr)
            sys.exit(1)
        seen_part_ann_ids.add(p_id)

        if p_id in ambig_part_ann_ids:
            print(f"VALIDATION FAILED: Part annotation ID {p_id} appears in both accepted and ambiguous lists", file=sys.stderr)
            sys.exit(1)

        parent_ann_id = assoc["parent_annotation_id"]
        if parent_ann_id not in spatial_by_id:
            print(f"VALIDATION FAILED: Accepted association references non-existent parent annotation ID {parent_ann_id}", file=sys.stderr)
            sys.exit(1)

        parent_rec = spatial_by_id[parent_ann_id]
        if assoc["source_image_id"] != parent_rec["source_image_id"]:
            print(f"VALIDATION FAILED: Part image_id {assoc['source_image_id']} != parent image_id {parent_rec['source_image_id']}", file=sys.stderr)
            sys.exit(1)

        if parent_rec["fashionpedia_category_id"] not in eligible_parents:
            print(f"VALIDATION FAILED: Parent category ID {parent_rec['fashionpedia_category_id']} is not eligible", file=sys.stderr)
            sys.exit(1)

        # Check geometry metrics math
        m = assoc["geometry_metrics"]
        if m["part_coverage"] < min_part_cov:
            print(f"VALIDATION FAILED: Accepted part {p_id} part_coverage ({m['part_coverage']}) < threshold ({min_part_cov})", file=sys.stderr)
            sys.exit(1)

        if req_centre_inside and not m["part_centre_inside"]:
            print(f"VALIDATION FAILED: Accepted part {p_id} centre is not inside parent", file=sys.stderr)
            sys.exit(1)

    print("3. Accepted part association rules, threshold bounds & uniqueness: PASSED")

    # 4. Individual spatial record rules & training_ready validation
    for r in all_spatial_recs:
        ann_id = r["source_annotation_id"]
        decision = r["decision"]

        # Validate label validity for evaluated heads
        for hname, lbl_info in r["labels"].items():
            if lbl_info is not None:
                lbl = lbl_info["label"]
                st = lbl_info["status"]
                if lbl not in valid_labels_per_head[hname]:
                    print(f"VALIDATION FAILED: Unknown label '{lbl}' for head '{hname}' in record {ann_id}", file=sys.stderr)
                    sys.exit(1)
                if st not in ("direct", "candidate_mapping"):
                    print(f"VALIDATION FAILED: Invalid mapping status '{st}' in record {ann_id}", file=sys.stderr)
                    sys.exit(1)

        if decision == "training_ready":
            # Every head must have non-null label
            for hname in target_heads:
                if r["labels"].get(hname) is None:
                    print(f"VALIDATION FAILED: training_ready record {ann_id} missing label for head '{hname}'", file=sys.stderr)
                    sys.exit(1)

            # All heads must be 'direct'
            for hname in target_heads:
                st = r["labels"][hname]["status"]
                if st != "direct":
                    print(f"VALIDATION FAILED: training_ready record {ann_id} has non-direct status '{st}' on head '{hname}'", file=sys.stderr)
                    sys.exit(1)

            # Check for conflict reason codes
            for rcode in r.get("reason_codes", []):
                if "CONFLICT_" in rcode or "MISSING_" in rcode or "MANUAL_REVIEW_" in rcode:
                    print(f"VALIDATION FAILED: training_ready record {ann_id} contains conflict/missing/manual reason code: {rcode}", file=sys.stderr)
                    sys.exit(1)

    print("4. Record schema, target taxonomy, and training_ready rules: PASSED")

    # 5. Source image split isolation (zero data-leakage)
    image_to_splits = {}
    for r in all_spatial_recs:
        img_id = r["source_image_id"]
        sp = r["split"]
        if img_id not in image_to_splits:
            image_to_splits[img_id] = set()
        image_to_splits[img_id].add(sp)

    cross_split_images = [img_id for img_id, splits in image_to_splits.items() if len(splits) > 1]
    if len(cross_split_images) > 0:
        print(f"VALIDATION FAILED: Data leakage detected across {len(cross_split_images)} images", file=sys.stderr)
        sys.exit(1)

    print("5. Source image split isolation (zero data-leakage): PASSED")

    # 6. summary.json totals match actual data
    if summary_data["base_instance_count"] != len(all_spatial_recs):
        print("VALIDATION FAILED: summary.json base_instance_count mismatch", file=sys.stderr)
        sys.exit(1)

    if summary_data["accepted_association_counts"]["total"] != len(accepted_assoc_recs):
        print("VALIDATION FAILED: summary.json accepted_association_counts mismatch", file=sys.stderr)
        sys.exit(1)

    if summary_data["ambiguous_association_counts"]["total"] != len(ambig_assoc_recs):
        print("VALIDATION FAILED: summary.json ambiguous_association_counts mismatch", file=sys.stderr)
        sys.exit(1)

    if summary_data["unassociated_part_counts"]["total"] != len(unassoc_parts_recs):
        print("VALIDATION FAILED: summary.json unassociated_part_counts mismatch", file=sys.stderr)
        sys.exit(1)

    if summary_data["decision_counts_after"]["training_ready"] != len(train_ready_recs):
        print("VALIDATION FAILED: summary.json training_ready count mismatch", file=sys.stderr)
        sys.exit(1)

    if summary_data["decision_counts_after"]["manual_review"] != len(manual_review_recs):
        print("VALIDATION FAILED: summary.json manual_review count mismatch", file=sys.stderr)
        sys.exit(1)

    if summary_data["decision_counts_after"]["rejected"] != len(rejected_recs):
        print("VALIDATION FAILED: summary.json rejected count mismatch", file=sys.stderr)
        sys.exit(1)

    print("6. spatial_summary.json totals & metrics match actual data: PASSED")
    print("==================================================")
    print("ALL SPATIAL MANIFEST VALIDATIONS PASSED CLEANLY!")
    print("==================================================")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Validate Fashionpedia spatial dataset manifest.")
    parser.add_argument("--manifest-dir", required=True, help="Path to spatial manifest output directory.")
    parser.add_argument("--base-manifest", required=True, help="Path to base manifest all_instances.jsonl.")
    parser.add_argument("--classes", required=True, help="Path to classes.json.")
    parser.add_argument("--association-config", required=True, help="Path to part_association.json.")

    args = parser.parse_args()
    validate_spatial_manifest(args.manifest_dir, args.base_manifest, args.classes, args.association_config)
